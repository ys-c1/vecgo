package raster

import (
	"errors"
	"fmt"
	"os"
	"sort"

	"vecgo/geom"
)

type Image struct {
	W, H int
	Pix  []uint8
}

func New(w, h int) (*Image, error) {
	if w <= 0 || h <= 0 {
		return nil, errors.New("画幅必须为正")
	}
	return &Image{W: w, H: h, Pix: make([]uint8, w*h)}, nil
}

// Clear zeroes the pixel buffer. It makes buffer-residue safety an explicit
// guarantee instead of relying on make's zero value or on Fill writing every
// index exactly once, so a reused Image cannot leak pixels from a prior run.
func (im *Image) Clear() {
	for i := range im.Pix {
		im.Pix[i] = 0
	}
}

// polygonKey renders a polygon's content as a stable string so polygons can be
// sorted deterministically. Iteration order then depends on geometry, not on
// the order the caller happened to supply the slice in.
func polygonKey(p []geom.Point) string {
	return fmt.Sprint(p)
}

func (im *Image) Fill(polys [][]geom.Point, supersample int) error {
	if supersample < 1 {
		return errors.New("supersample 必须为正")
	}
	for _, p := range polys {
		if len(p) < 3 {
			return errors.New("多边形至少三个顶点")
		}
	}
	// 确定性遍历：先按内容排序，保证同一组多边形无论调用方给的顺序如何，
	// 命中测试（含首个命中即 break）都按同一顺序执行。
	ordered := make([][]geom.Point, len(polys))
	copy(ordered, polys)
	sort.SliceStable(ordered, func(i, j int) bool {
		return polygonKey(ordered[i]) < polygonKey(ordered[j])
	})
	polys = ordered
	// 显式清缓冲，杜绝复用 Image 时的残留像素。
	im.Clear()
	minx, miny := polys[0][0].X, polys[0][0].Y
	maxx, maxy := minx, miny
	for _, p := range polys {
		for _, q := range p {
			if q.X < minx {
				minx = q.X
			}
			if q.X > maxx {
				maxx = q.X
			}
			if q.Y < miny {
				miny = q.Y
			}
			if q.Y > maxy {
				maxy = q.Y
			}
		}
	}
	spanx, spany := maxx-minx, maxy-miny
	if spanx == 0 {
		spanx = 1
	}
	if spany == 0 {
		spany = 1
	}
	den := supersample * supersample
	for row := 0; row < im.H; row++ {
		for col := 0; col < im.W; col++ {
			hit := 0
			for sj := 0; sj < supersample; sj++ {
				for si := 0; si < supersample; si++ {
					px := minx + (float64(col)+(float64(si)+0.5)/float64(supersample))*spanx/float64(im.W)
					py := miny + (float64(row)+(float64(sj)+0.5)/float64(supersample))*spany/float64(im.H)
					for _, p := range polys {
						if geom.Inside(p, px, py) {
							hit++
							break
						}
					}
				}
			}
			im.Pix[row*im.W+col] = uint8(255 * hit / den)
		}
	}
	return nil
}

func (im *Image) SavePGM(path string) error {
	if im.W == 0 || im.H == 0 {
		return errors.New("空图不能导出")
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := fmt.Fprintf(f, "P5\n%d %d\n255\n", im.W, im.H); err != nil {
		return err
	}
	_, err = f.Write(im.Pix)
	return err
}

func (im *Image) CountOn(threshold uint8) int {
	n := 0
	for _, v := range im.Pix {
		if v >= threshold {
			n++
		}
	}
	return n
}
